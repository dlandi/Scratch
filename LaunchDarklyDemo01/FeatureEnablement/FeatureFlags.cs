namespace FeatureEnablement;

/// <summary>
/// Constants for feature flag keys used in the demo application.
/// </summary>
public static class FeatureFlags
{
    /// <summary>
    /// When enabled, the hero section uses a dark color scheme instead of light.
    /// </summary>
    public const string HeroDarkMode = "hero-dark-mode";

    /// <summary>
    /// When enabled, the page background changes from off-white to cream color.
    /// </summary>
    public const string CreamBackground = "cream-background";

    /// <summary>
    /// When enabled, the main title changes from "The Best Travel Agency"
    /// to "The Very Best Travel Agency".
    /// </summary>
    public const string EnhancedTitle = "enhanced-title";
}
